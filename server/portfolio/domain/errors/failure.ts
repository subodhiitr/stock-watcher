export type DomainFailureCode = (typeof DOMAIN_FAILURE_CODES)[number]
export type Retryability = 'NEVER' | 'AFTER_STATE_REFRESH' | 'AFTER_CORRECTION'

export type DomainFailure<Code extends string = DomainFailureCode> = Readonly<{
  code: Code
  retryability: Retryability
  field?: string
  context: SafeContext
}>

export function domainFailure(
  code: DomainFailureCode,
  options: Readonly<{
    retryability?: Retryability
    field?: string
    context?: Readonly<Record<string, SafeContextValue | undefined>>
  }> = {},
): DomainFailure {
  const value: {
    code: DomainFailureCode
    retryability: Retryability
    field?: string
    context: SafeContext
  } = {
    code,
    retryability: options.retryability ?? 'AFTER_CORRECTION',
    context: createSafeContext(options.context),
  }
  if (options.field !== undefined) {
    value.field = options.field
  }
  return Object.freeze(value)
}
