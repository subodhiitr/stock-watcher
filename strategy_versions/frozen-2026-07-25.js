function stableSettingsJson(settings) {
  const frozenKeys = Object.keys(TradeRules.DEFAULT_SETTINGS).sort();
  return JSON.stringify(Object.fromEntries(frozenKeys.map(key => [key, settings[key]])));
}

function settingsSha256(settings) {
  return crypto.createHash('sha256').update(stableSettingsJson(settings)).digest('hex');
}

function loadFrozenSettings({ capital = 1000000 } = {}) {
  const settings = TradeRules.withDefaults({ ...OVERRIDES });
  const actualHash = settingsSha256(settings);
  if (actualHash !== EXPECTED_SETTINGS_SHA256) {
    throw new Error(
      `Frozen strategy ${STRATEGY_ID} no longer matches its audited settings: expected ${EXPECTED_SETTINGS_SHA256}, got ${actualHash}`
    );
  }
  settings.PORTFOLIO_INITIAL_CAPITAL = Number(capital);
  settings.PORTFOLIO_AVAILABLE_CASH = Number(capital);
  settings.PORTFOLIO_CAPITAL_SOURCE = STRATEGY_ID;
  settings.REPLAY_SKIP_OPPORTUNITIES = true;
  return settings;
}

